# Звания по уровню: (минимальный уровень, название) — этап 8
RANKS = [
    (1, "Новичок"),
    (3, "Юный криптонавт"),
    (5, "Трейдер"),
    (8, "Аналитик"),
    (12, "Крипто-гуру"),
    (18, "Легенда рынка"),
]


def get_rank(level: int) -> str:
    """Возвращает звание для уровня."""
    rank = RANKS[0][1]
    for min_level, name in RANKS:
        if level >= min_level:
            rank = name
    return rank